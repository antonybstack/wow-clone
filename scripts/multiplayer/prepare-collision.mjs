/** Reproduce server collision from the same world-space triangles/boxes and
 * 512-triangle partitions used by the playable client's background worker.
 * This is an export, not another terrain generator or height/clamp substitute.
 */
import fs from "node:fs/promises";
import path from "node:path";
import { createHash } from "node:crypto";
import { buildChurchyard } from "../../src/ashen-reach/scene.js";
import { partitionWorld } from "../../src/ashen-reach/world-partition.js";
const originalFetch = globalThis.fetch;
globalThis.fetch = (url, options) =>
  typeof url === "string" && url.startsWith("/")
    ? fs.readFile(path.join("public", url)).then((bytes) => new Response(bytes))
    : originalFetch(url, options);
const source = await buildChurchyard(null, null, { dataOnly: true });
const partition = partitionWorld(source),
  buffers = [],
  chunks = [];
let offset = 0;
for (const block of partition.batches) {
  const mesh = partition.meshes[block.meshId];
  if (!mesh.collision) continue;
  const p = block.buffers.positions,
    i = block.buffers.indices;
  chunks.push({
    name: mesh.name,
    positionOffset: offset,
    positionCount: p.length,
    indexOffset: offset + p.byteLength,
    indexCount: i.length,
  });
  buffers.push(
    Buffer.from(p.buffer, p.byteOffset, p.byteLength),
    Buffer.from(i.buffer, i.byteOffset, i.byteLength),
  );
  offset += p.byteLength + i.byteLength;
}
const hash = (b) => createHash("sha256").update(b).digest("hex"),
  bytes = Buffer.concat(buffers),
  sha256 = hash(bytes);
const starter = JSON.parse(
  await fs.readFile("public/ashen-reach/startup/starter/manifest.json"),
);
const metadata = {
  schema: 1,
  lite: "1.31.1",
  havok: "1.3.14",
  sourceHash: starter.provenance.sha256,
  data: { file: `collision-${sha256}.bin`, sha256, bytes: bytes.length },
  chunks,
  boxes: source.boxes,
};
const json = Buffer.from(JSON.stringify(metadata)),
  metadataHash = hash(json),
  root = "public/ashen-reach/presence-v1";
await fs.mkdir(root, { recursive: true });
await fs.writeFile(`${root}/${metadata.data.file}`, bytes);
await fs.writeFile(`${root}/collision-${metadataHash}.json`, json);
const release = {
  schema: 1,
  protocol: "ashen-presence-v1",
  collisionHash: metadataHash,
  sourceHash: metadata.sourceHash,
  file: `collision-${metadataHash}.json`,
  bytes: json.length,
  data: metadata.data,
};
await fs.writeFile(`${root}/manifest.json`, JSON.stringify(release, null, 2));
await fs.writeFile(
  "src/multiplayer/collision-release.js",
  `// Generated by scripts/multiplayer/prepare-collision.mjs; regenerate after world or lock changes.\nexport const COLLISION_RELEASE=Object.freeze(${JSON.stringify(release, null, 2)});\n`,
);
console.log(
  JSON.stringify({
    chunks: chunks.length,
    boxes: source.boxes.length,
    binaryBytes: bytes.length,
    metadataBytes: json.length,
    collisionHash: metadataHash,
  }),
);
