import {chromium} from 'playwright';
import { CDP_URL } from '../lib/cdp.mjs';
import fs from 'node:fs/promises';
const browser = await chromium.connectOverCDP(CDP_URL);
const page = browser.contexts()[0].pages().find(p => p.url().includes('ashen-reach.html'));
await page.bringToFront();
await page.goto((process.env.ASHEN_URL||'http://127.0.0.1:5173/ashen-reach.html?play&clean'), {waitUntil:'commit', timeout:60000});
await page.waitForFunction(() => globalThis.ASHEN?.ready, null, {timeout:60000});
await page.waitForTimeout(700);
await page.evaluate(async()=>{await ASHEN.equipment.equipPreset('warden');});
await page.waitForTimeout(1200);
const data = await page.evaluate(() => {
  const s = ASHEN.combat.fx.sockets, bw = ASHEN.player.body.worldMatrix;
  const xf = (m,x,y,z)=>[m[0]*x+m[4]*y+m[8]*z+m[12], m[1]*x+m[5]*y+m[9]*z+m[13], m[2]*x+m[6]*y+m[10]*z+m[14]];
  const hw = n => {
    const bone = ASHEN.body.skeleton.bones.find(x=>x.name===n);
    if (!bone) return {err:'no-bone:'+n};
    const c = s.toCapsule(bone);
    if (!c) return {err:'no-capsule:'+n};
    return xf(bw, c.x, c.y, c.z);
  };
  const root = ASHEN.scene.meshes.find(m=>m.name==='greatstaffWood')?.parent;
  const propWm = root?.worldMatrix;
  const mainSocket = s.sockets.mainHand.node;
  const offSocket = s.sockets.offHand.node;
  const mainWm = mainSocket.worldMatrix;
  const offWm = offSocket.worldMatrix;
  const twoHand = ASHEN.body.animationGroups.find(g=>g.name==='Walk_Carry_Loop');
  const out = {};
  out.leftHand = hw('mixamorig:LeftHand');
  out.rightHand = hw('mixamorig:RightHand');
  out.leftFore = hw('mixamorig:LeftForeArm');
  out.rightFore = hw('mixamorig:RightForeArm');
  out.propW = propWm ? Array.from(propWm) : 'MISSING';
  out.mainW = mainWm ? Array.from(mainWm) : 'MISSING';
  out.offW = offWm ? Array.from(offWm) : 'MISSING';
  out.carryTime = twoHand ? twoHand.currentTime : 'MISSING';
  out.carryWeight = twoHand ? twoHand.weight : 'MISSING';
  return out;
});
console.log(JSON.stringify(data, null, 2));
await fs.writeFile('.cache/armed-repair/probes/baseline-geom.json', JSON.stringify(data, null, 2));
await browser.close();
